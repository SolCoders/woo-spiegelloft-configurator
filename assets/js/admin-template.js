(function ($) {
	'use strict';

	function bindAccordion() {
		$(document).on('click', '.wcs-template-accordion .wcs-accordion-toggle', function (e) {
			e.preventDefault();
			var $panel = $(this).closest('.wcs-accordion-panel');
			var expanded = $(this).attr('aria-expanded') === 'true';
			$(this).attr('aria-expanded', expanded ? 'false' : 'true');
			$panel.toggleClass('is-open', !expanded);
		});

		$(document).on('change', '.wcs-group-toggle', function () {
			$(this).closest('.wcs-template-group-panel').toggleClass('is-enabled', $(this).is(':checked'));
		});
	}

	function slugify(value) {
		return String(value || '')
			.toLowerCase()
			.trim()
			.replace(/[^a-z0-9]+/g, '-')
			.replace(/^-+|-+$/g, '');
	}

	function bindTemplateSlug() {
		var $title = $('#title');
		var $slug = $('#wcs_template_slug');

		if (!$title.length || !$slug.length) {
			return;
		}

		var autoGenerated = !$slug.val() || $slug.val() === 'auto-draft';

		function syncSlug() {
			if (!autoGenerated) {
				return;
			}

			$slug.val(slugify($title.val()));
		}

		syncSlug();
		$title.on('input', syncSlug);
		$slug.on('input', function () {
			autoGenerated = false;
		});
	}

	function reindexSideMeasurements() {
		$('.wcs-side-list .wcs-side-row').each(function (index) {
			$(this).find('[name]').each(function () {
				$(this).attr('name', $(this).attr('name').replace(/wcs_side_measurements\[\d+\]/, 'wcs_side_measurements[' + index + ']'));
			});
		});
	}

	function buildSideMeasurementRow($source) {
		var $row = $source && $source.length ? $source.clone() : $('<div class="wcs-side-row">' +
			'<label>Label<input type="text" class="wcs-side-label" name="wcs_side_measurements[0][label]" placeholder="Mirror size"></label>' +
			'<label>Key<input type="text" class="wcs-side-key" name="wcs_side_measurements[0][key]" placeholder="mirror-size"></label>' +
			'<label>Min<input type="number" name="wcs_side_measurements[0][min]" value="400" min="0"></label>' +
			'<label>Max<input type="number" name="wcs_side_measurements[0][max]" value="2500" min="0"></label>' +
			'<button type="button" class="button wcs-side-add">Add</button>' +
			'<button type="button" class="button wcs-side-remove">Remove</button>' +
			'</div>');

		if ($source && $source.length) {
			$row.find('input').each(function (index) {
				$(this).val($source.find('input').eq(index).val());
			});
			$row.find('.wcs-side-label').val('');
			$row.find('.wcs-side-key').val('');
		}

		return $row;
	}

	function bindSideMeasurements() {
		$(document).on('click', '.wcs-side-add', function (e) {
			e.preventDefault();
			var $row = $(this).closest('.wcs-side-row');
			$row.after(buildSideMeasurementRow($row));
			reindexSideMeasurements();
		});

		$(document).on('click', '.wcs-side-remove', function (e) {
			e.preventDefault();
			var $list = $(this).closest('.wcs-side-list');
			if ($list.find('.wcs-side-row').length <= 1) {
				$(this).closest('.wcs-side-row').find('input[type="text"]').val('');
				$(this).closest('.wcs-side-row').find('input[name$="[min]"]').val('400');
				$(this).closest('.wcs-side-row').find('input[name$="[max]"]').val('2500');
				return;
			}
			$(this).closest('.wcs-side-row').remove();
			reindexSideMeasurements();
		});

		$(document).on('blur', '.wcs-side-label', function () {
			var $row = $(this).closest('.wcs-side-row');
			var $key = $row.find('.wcs-side-key');
			if (!$key.val()) {
				$key.val(slugify($(this).val()));
			}
		});
	}

	function refreshChoicePagination($table) {
		var perPage = parseInt($table.data('per-page'), 10) || 8;
		var page = parseInt($table.data('page'), 10) || 1;
		var query = String($table.closest('.wcs-template-flat-panel').find('.wcs-choice-search').val() || '').toLowerCase().trim();
		var $rows = $table.find('tbody tr');
		var $matches = $rows.filter(function () {
			return !query || String($(this).data('choice-search') || '').indexOf(query) !== -1;
		});
		var totalPages = Math.max(1, Math.ceil($matches.length / perPage));
		page = Math.min(Math.max(1, page), totalPages);
		$table.data('page', page);

		$rows.hide();
		$matches.slice((page - 1) * perPage, page * perPage).show();

		var $panel = $table.closest('.wcs-template-flat-panel');
		$panel.find('.wcs-choice-page-status').text(page + ' / ' + totalPages);
		$panel.find('.wcs-choice-page-prev').prop('disabled', page <= 1);
		$panel.find('.wcs-choice-page-next').prop('disabled', page >= totalPages);
		$panel.find('.wcs-template-flat-empty').prop('hidden', $matches.length > 0).toggle($matches.length === 0);
	}

	function refreshChoiceOrder($table) {
		$table.find('tbody tr').each(function () {
			var $row = $(this);
			var choiceId = $row.data('choice-id') || $row.find('input[name^="wcs_extra_option_map"]').val();
			$row.find('input[name="wcs_choice_order[]"]').val(choiceId || '');
		});
	}

	function bindChoiceListTools() {
		$('.wcs-option-table').each(function () {
			refreshChoicePagination($(this));
		});

		$(document).on('input', '.wcs-choice-search', function () {
			var $table = $(this).closest('.wcs-template-flat-panel').find('.wcs-option-table');
			$table.data('page', 1);
			refreshChoicePagination($table);
		});

		$(document).on('click', '.wcs-choice-page-prev, .wcs-choice-page-next', function (e) {
			e.preventDefault();
			var $table = $(this).closest('.wcs-template-flat-panel').find('.wcs-option-table');
			var page = parseInt($table.data('page'), 10) || 1;
			$table.data('page', $(this).hasClass('wcs-choice-page-next') ? page + 1 : page - 1);
			refreshChoicePagination($table);
		});
	}

	function reindexRules() {
		$('#wcs-rules-list .wcs-rule-row').each(function (index) {
			$(this).find('[name]').each(function () {
				var name = $(this).attr('name');
				if (!name) {
					return;
				}
				$(this).attr('name', name.replace(/wcs_validation_rules\[\d+\]/, 'wcs_validation_rules[' + index + ']'));
			});
		});
	}

	function setRuleDefaults($row) {
		var type = $row.find('.wcs-rule-type').val();
		var $action = $row.find('.wcs-rule-action');
		var defaults = {
			required: 'require',
			block: 'disallow_value',
			visibility: 'show',
			clear: 'clear',
			range: 'validate_range',
			disable: 'disable_option'
		};

		if (defaults[type]) {
			$action.val(defaults[type]);
		}
	}

	function toggleRuleFields($row) {
		var type = $row.find('.wcs-rule-type').val();
		var source = $row.find('.wcs-rule-source').val();
		var operator = $row.find('.wcs-rule-operator').val();
		var action = $row.find('.wcs-rule-action').val();

		$row.attr({
			'data-rule-type': type,
			'data-source': source,
			'data-then': action
		});

		$row.find('[data-visible-for-source]').each(function () {
			var allowed = String($(this).data('visible-for-source')).split(' ');
			$(this).toggle(allowed.indexOf(source) !== -1);
		});

		$row.find('[data-visible-for-operator]').each(function () {
			var allowed = String($(this).data('visible-for-operator')).split(' ');
			$(this).toggle(allowed.indexOf(operator) !== -1);
		});

		$row.find('[data-visible-for-action]').each(function () {
			var allowed = String($(this).data('visible-for-action')).split(' ');
			$(this).toggle(allowed.indexOf(action) !== -1);
		});

		var summaries = {
			required: 'Use this for "if X is chosen, Y must be filled".',
			block: 'Use this to prevent a category or option from being selected.',
			visibility: 'Use this for storefront show/hide behavior.',
			clear: 'Use this to reset child values when a parent changes.',
			range: 'Use this for min/max numeric formulas.',
			disable: 'Use this to disable an option while keeping it visible.'
		};
		$row.find('.wcs-rule-summary').text(summaries[type] || '');
	}

	function refreshRuleBuilder() {
		$('#wcs-rules-list .wcs-rule-row').each(function () {
			toggleRuleFields($(this));
		});
	}

	function bindRuleBuilder() {
		$('#wcs-add-rule').on('click', function (e) {
			e.preventDefault();
			var $row = $('#wcs-rules-list .wcs-rule-row').first().clone();
			$row.find('input[type="text"], input[type="number"]').val('');
			$row.find('input[type="checkbox"]').prop('checked', false);
			$row.find('select').each(function () {
				this.selectedIndex = 0;
			});
			$('#wcs-rules-list').append($row);
			reindexRules();
			setRuleDefaults($row);
			toggleRuleFields($row);
		});

		$(document).on('change', '.wcs-rule-type', function () {
			var $row = $(this).closest('.wcs-rule-row');
			setRuleDefaults($row);
			toggleRuleFields($row);
		});

		$(document).on('change', '.wcs-rule-source, .wcs-rule-operator, .wcs-rule-action', function () {
			toggleRuleFields($(this).closest('.wcs-rule-row'));
		});

		$(document).on('click', '.wcs-remove-rule', function (e) {
			e.preventDefault();
			var $list = $('#wcs-rules-list');
			if ($list.find('.wcs-rule-row').length <= 1) {
				$list.find('input, select').val('');
				refreshRuleBuilder();
				return;
			}
			$(this).closest('.wcs-rule-row').remove();
			reindexRules();
		});

		refreshRuleBuilder();
	}

	function bindDeleteChoice() {
		$(document).on('click', '.wcs-delete-choice', function (e) {
			e.preventDefault();

			var $button = $(this);
			var choiceId = parseInt($button.data('choice-id'), 10);
			var nonce = $button.data('nonce');
			var labels = window.wcsAdmin && wcsAdmin.i18n ? wcsAdmin.i18n : {};

			if ($button.data('busy')) {
				return;
			}

			if (!choiceId || !nonce) {
				window.location.href = $button.attr('href');
				return;
			}

			if (!window.confirm(labels.deleteConfirm || 'Delete this choice?')) {
				return;
			}

			$button.data('busy', true).addClass('disabled').text(labels.deleting || 'Deleting...');

			$.post(wcsAdmin.ajaxUrl, {
				action: 'wcs_delete_choice',
				choice_id: choiceId,
				nonce: nonce
			})
				.done(function (response) {
					if (!response || !response.success) {
						window.alert(response && response.data && response.data.message ? response.data.message : (labels.error || 'An error occurred.'));
						return;
					}

					var $row = $button.closest('tr');
					var $panel = $button.closest('.wcs-template-group-panel, .wcs-template-flat-panel');
					var $tbody = $row.closest('tbody');

					$row.fadeOut(150, function () {
						$(this).remove();

						var count = $tbody.find('tr').length;
						var $count = $panel.find('.wcs-choice-count').first();
						$count.data('count', count).text(count === 1 ? '1 choice' : count + ' choices');

						if (!count) {
							$panel.find('.wcs-option-table-wrap').hide();
							$panel.find('.wcs-empty-options-message, .wcs-template-flat-empty').prop('hidden', false).show();
						}
					});
				})
				.fail(function () {
					window.alert(labels.error || 'An error occurred.');
				})
				.always(function () {
					$button.data('busy', false).removeClass('disabled').text(labels.deleteLabel || 'Delete');
				});
		});
	}

	function bindChoiceSorting() {
		$('.wcs-option-table tbody').each(function () {
			var $tbody = $(this);
			if ($tbody.data('sortable')) {
				return;
			}
			$tbody.sortable({
				axis: 'y',
				handle: '.wcs-choice-sort-handle',
				items: 'tr',
				placeholder: 'wcs-choice-sort-placeholder',
				forcePlaceholderSize: true,
				start: function () {
					$tbody.closest('.wcs-option-table').addClass('is-sorting');
				},
				helper: function (e, row) {
					var $originals = row.children();
					var $helper = row.clone();
					$helper.addClass('wcs-choice-sort-helper');
					$helper.children().each(function (index) {
						$(this).width($originals.eq(index).width());
					});
					return $helper;
				},
				stop: function () {
					var $table = $tbody.closest('.wcs-option-table');
					refreshChoiceOrder($table);
					$table.removeClass('is-sorting');
					refreshChoicePagination($table);
				}
			});
			$tbody.data('sortable', true);
		});

		$(document).on('submit', 'form#post, form[name="post"]', function () {
			$('.wcs-option-table').each(function () {
				refreshChoiceOrder($(this));
			});
		});
	}

	function bindGroupSorting() {
		$('.wcs-template-choices .wcs-template-accordion').each(function () {
			var $accordion = $(this);
			if ($accordion.data('sortable')) {
				return;
			}
			$accordion.sortable({
				axis: 'y',
				handle: '.wcs-group-sort-handle',
				items: '> .wcs-template-group-panel',
				placeholder: 'wcs-group-sort-placeholder',
				forcePlaceholderSize: true
			});
			$accordion.data('sortable', true);
		});
	}

	function slugifyInlinePosition(value) {
		return String(value || '')
			.toLowerCase()
			.trim()
			.replace(/[^a-z0-9]+/g, '-')
			.replace(/^-+|-+$/g, '');
	}

	function buildInlinePositionRow() {
		return $('<div class="wcs-inline-position-option">' +
			'<input type="text" class="wcs-inline-position-option-label" placeholder="top center">' +
			'<input type="text" class="wcs-inline-position-option-value" placeholder="top-center">' +
			'<button type="button" class="button wcs-inline-position-add">+</button>' +
			'<button type="button" class="button wcs-inline-position-remove">-</button>' +
			'</div>');
	}

	function collectInlinePositions($wrap) {
		var rows = [];
		$wrap.find('.wcs-inline-position-option').each(function () {
			var label = $(this).find('.wcs-inline-position-option-label').val();
			var value = $(this).find('.wcs-inline-position-option-value').val();
			if (label || value) {
				rows.push({ label: label, value: value });
			}
		});
		return rows;
	}

	function bindInlinePositions() {
		$(document).on('change', '.wcs-inline-position-enabled', function () {
			var enabled = $(this).is(':checked');
			$(this).closest('.wcs-inline-positions').toggleClass('is-enabled', enabled);
		});

		$(document).on('click', '.wcs-inline-position-add', function (e) {
			e.preventDefault();
			$(this).closest('.wcs-inline-position-options').append(buildInlinePositionRow());
		});

		$(document).on('click', '.wcs-inline-position-remove', function (e) {
			e.preventDefault();
			var $rows = $(this).closest('.wcs-inline-position-options').find('.wcs-inline-position-option');
			if ($rows.length <= 1) {
				$(this).closest('.wcs-inline-position-option').find('input').val('');
				return;
			}
			$(this).closest('.wcs-inline-position-option').remove();
		});

		$(document).on('blur', '.wcs-inline-position-option-label', function () {
			var $row = $(this).closest('.wcs-inline-position-option');
			var $value = $row.find('.wcs-inline-position-option-value');
			if (!$value.val()) {
				$value.val(slugifyInlinePosition($(this).val()));
			}
		});

		$(document).on('click', '.wcs-inline-position-save', function (e) {
			e.preventDefault();
			var $button = $(this);
			var $wrap = $button.closest('.wcs-inline-positions');
			var labels = window.wcsAdmin && wcsAdmin.i18n ? wcsAdmin.i18n : {};
			$button.prop('disabled', true);
			$wrap.find('.wcs-inline-position-status').text(labels.saving || 'Saving...');

			$.post(wcsAdmin.ajaxUrl, {
				action: $wrap.data('group') ? 'wcs_save_group_positions' : 'wcs_save_choice_positions',
				group: $wrap.data('group') || '',
				choice_id: $wrap.data('choice-id'),
				nonce: $wrap.data('nonce'),
				enabled: $wrap.find('.wcs-inline-position-enabled').is(':checked') ? 1 : 0,
				label: $wrap.find('.wcs-inline-position-label').val(),
				show_when: $wrap.find('.wcs-inline-position-condition').val() || '',
				positions: collectInlinePositions($wrap)
			})
				.done(function (response) {
					$wrap.find('.wcs-inline-position-status').text(response && response.success ? (labels.saved || 'Saved.') : (response.data && response.data.message ? response.data.message : (labels.error || 'An error occurred.')));
				})
				.fail(function () {
					$wrap.find('.wcs-inline-position-status').text(labels.error || 'An error occurred.');
				})
				.always(function () {
					$button.prop('disabled', false);
				});
		});
	}

	$(function () {
		bindAccordion();
		bindTemplateSlug();
		bindSideMeasurements();
		bindRuleBuilder();
		bindDeleteChoice();
		bindChoiceSorting();
		bindGroupSorting();
		bindChoiceListTools();
		bindInlinePositions();
	});
}(jQuery));
